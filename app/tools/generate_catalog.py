"""Generate the Kotlin vocabulary from word_packs.json; --check detects drift."""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "src/main/java/com/guguabc/kids/data/Words.kt"


def render() -> str:
    data = json.loads((ROOT / "tools/word_packs.json").read_text(encoding="utf-8"))
    quote = lambda value: json.dumps(value, ensure_ascii=False)
    lines = [
        "package com.guguabc.kids.data", "",
        "import androidx.annotation.DrawableRes", "import androidx.annotation.RawRes",
        "import com.guguabc.kids.R", "",
        "/** Generated by tools/generate_catalog.py from tools/word_packs.json. */",
        "enum class LearningCategory(val id: String, val title: String, val english: String, val heading: String, val heroIds: List<String>) {",
    ]
    for category in data["categories"]:
        fields = ", ".join(quote(category[k]) for k in ("id", "name", "en", "title"))
        heroes = ", ".join(map(quote, category["hero"]))
        lines.append(f'    {category["id"].upper()}({fields}, listOf({heroes})),')
    lines += ["}", "", "data class Word(",
              "    val id: String,", "    val en: String,", "    val zh: String,",
              "    val packId: String,", "    val level: String,", "    val group: String,",
              "    @DrawableRes val imageRes: Int,", "    @RawRes val audioRes: Int,", ")", "",
              "data class WordPack(", "    val id: String,", "    val no: Int,",
              "    val title: String,", "    val level: String,", "    val words: List<Word>,",
              "    val category: LearningCategory = LearningCategory.ANIMALS,", ")", "", "object Words {",
              '    const val DEFAULT_PACK_ID = "p1_friends"', ""]
    consts = {p["id"]: f'P{i + 1}' for i, p in enumerate(data["packs"])}
    for pid, const in consts.items():
        lines.append(f"    const val {const} = {quote(pid)}")
    lines += ["", "    val all: List<Word> = listOf("]
    for word in data["words"]:
        fields = ", ".join(quote(word[k]) for k in ("id", "en", "zh"))
        lines.append(f'        Word({fields}, {consts[word["pack"]]}, {quote(word["level"])}, {quote(word["group"])}, R.drawable.{Path(word["image"]).stem}, R.raw.{Path(word["audio"]).stem}),')
    lines += ["    )", "", "    val packs: List<WordPack> = listOf("]
    for p in data["packs"]:
        indices = [next(i for i, w in enumerate(data["words"]) if w["id"] == wid) for wid in p["words"]]
        assert len(indices) == 3 and indices == list(range(indices[0], indices[0] + 3))
        lines.append(f'        WordPack({consts[p["id"]]}, {p["no"]}, {quote(p["title"])}, {quote(p["level"])}, all.slice({indices[0]}..{indices[-1]}), LearningCategory.{p["category"].upper()}),')
    lines += ["    )", "",
              "    fun of(packId: String): WordPack = packs.firstOrNull { it.id == packId } ?: packs.first()",
              "    fun byId(id: String): Word? = all.firstOrNull { it.id == id }",
              "    fun inCategory(category: LearningCategory): List<WordPack> = packs.filter { it.category == category }",
              "}", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    expected = render()
    if "--check" in sys.argv:
        if TARGET.read_text(encoding="utf-8") != expected:
            raise SystemExit("Words.kt differs from word_packs.json; run tools/generate_catalog.py")
        print("Catalog matches generated Kotlin")
    else:
        TARGET.write_text(expected, encoding="utf-8")
        print(TARGET)
